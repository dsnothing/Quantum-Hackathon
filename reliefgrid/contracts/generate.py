"""Regenerate wire JSON schemas and TypeScript without a Node dependency."""
from pathlib import Path
import json
from reliefgrid.backend.domain import Scenario, PlanningRequest, PreparedProblem, PlanResult

ROOT = Path(__file__).resolve().parent


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(v) for v in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return f"({ts(schema['items'])})[]"
    if kind == "object":
        if "properties" in schema:
            required = schema.get("required", [])
            return "{\n" + "\n".join(f"  {k}{'' if k in required else '?'}: {ts(v)};" for k,v in schema["properties"].items()) + "\n}"
        additional = schema.get("additionalProperties", {})
        return "Record<string, " + (ts(additional) if isinstance(additional, dict) else "unknown") + ">"
    return {"string":"string", "number":"number", "integer":"number", "boolean":"boolean", "null":"null"}.get(kind, "unknown")


def generate():
    definitions = {}
    for model in (Scenario, PlanningRequest, PreparedProblem, PlanResult):
        schema = model.model_json_schema()
        (ROOT / f"{model.__name__}.schema.json").write_text(json.dumps(schema, indent=2) + "\n", encoding="utf-8")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    output = "// Generated by python -m reliefgrid.contracts.generate. Do not edit.\n"
    output += "\n\n".join(f"export type {name} = {ts(schema)};" for name, schema in sorted(definitions.items())) + "\n"
    (ROOT / "types.ts").write_text(output, encoding="utf-8")


if __name__ == "__main__":
    generate()
