"""Deterministically regenerate the original, fictional demonstration geography."""
import json
from pathlib import Path

HERE = Path(__file__).parent


def write(name, value):
    (HERE / name).write_text(json.dumps(value, indent=2) + "\n", encoding="utf-8")


def build():
    # Coordinates locate a fictional region; they do not describe real roads.
    xs = [-79.974, -79.963, -79.952, -79.943, -79.925, -79.914, -79.903]
    ys = [43.538, 43.530, 43.522, 43.514, 43.506]
    nodes = [{"id": f"n{r * 7 + c:02}", "lon": x, "lat": y}
             for r, y in enumerate(ys) for c, x in enumerate(xs)]
    nodes += [{"id": f"n{35 + i:02}", "lon": x, "lat": y} for i, (x, y) in enumerate([
        (-79.891, 43.530), (-79.880, 43.534), (-79.880, 43.522),
        (-79.888, 43.512), (-79.934, 43.546)])]
    by_id = {node["id"]: node for node in nodes}
    edges = []

    def road(edge_id, a, b, minutes, both=True):
        aa, bb = by_id[f"n{a:02}"], by_id[f"n{b:02}"]
        edges.append({"id": edge_id, "fromNodeId": aa["id"], "toNodeId": bb["id"],
                      "travelMinutes": minutes, "bidirectional": both,
                      "geometry": {"type": "LineString", "coordinates": [
                          [aa["lon"], aa["lat"]], [bb["lon"], bb["lat"]]]}})

    for r in range(5):
        for c in range(6):
            if c == 3:
                if r == 2:
                    road("bridge-main", r * 7 + c, r * 7 + c + 1, 1.4)
            else:
                road(f"road-h-{r}-{c}", r * 7 + c, r * 7 + c + 1, 1.8)
    for r in range(4):
        for c in range(7):
            road(f"road-v-{r}-{c}", r * 7 + c, (r + 1) * 7 + c, 1.5)
    road("east-ridge", 13, 35, 2.4)
    road("ridge-oneway", 35, 36, 1.5, False)
    road("ridge-descent", 36, 37, 2.0, False)
    road("orchard-road", 37, 38, 1.7)
    road("orchard-return", 38, 27, 2.4)
    # Rural travel includes access/turn delays, not straight-line driving speed.
    # This scale creates a genuine three-hub tradeoff at a 12-minute threshold.
    for edge in edges:
        edge["travelMinutes"] = round(edge["travelMinutes"] * 2.5, 3)
    community_nodes = [0, 2, 7, 10, 14, 17, 21, 29, 32, 6, 12, 20, 34, 37, 39]
    populations = [430, 690, 520, 830, 610, 970, 460, 780, 680, 540, 890, 720, 560, 380, 140]
    communities = [{"id": f"community-{i + 1:02}", "nodeId": f"n{n:02}",
                    "population": population, "priorityMultiplier": 1.0}
                   for i, (n, population) in enumerate(zip(community_nodes, populations))]
    hubs = [{"id": f"hub-{i + 1:02}", "nodeId": f"n{n:02}"}
            for i, n in enumerate([8, 16, 23, 30, 5, 18, 26, 35])]
    for community, name in zip(communities, ["Cedar Grove", "Northgate", "Mill Quarter", "Old Town",
            "Westbank", "Bridgeview", "Willow Fields", "South Meadows", "East Gardens", "Pinecrest",
            "Riverside East", "Harbour End", "Orchard South", "Ridge Hamlet", "Alder Island"]):
        community["name"] = name
    for hub, name in zip(hubs, ["Cedar depot", "Civic hall", "Westbank school", "South fairgrounds",
            "North fire hall", "East bridge depot", "Orchard warehouse", "Ridge station"]):
        hub["name"] = name
    base = {"schemaVersion": "1", "id": "riverbend", "title": "Riverbend district",
            "description": "Choose supply hubs across two riverbanks. The Alder Bridge is the only crossing; Alder Island has no road access.",
            "crs": "EPSG:4326", "provenance": {"kind": "synthetic", "sources": [
                "Original ReliefGrid demonstration fixture; generated by generate_fixtures.py"],
                "license": "CC0-1.0", "transformationNotes":
                "Fictional geography, roads, populations and travel times. No real emergency data. "
                "Travel times are illustrative fixed minutes; no congestion, capacities or flood prediction. "
                "Bridge closure removes both directions. Island n39 has no road access. "
                "All priority multipliers equal 1; policy weighting is not inferred from geography."},
            "nodes": nodes, "edges": edges, "communities": communities, "candidateHubs": hubs}
    write("riverbend.json", base)
    upland = json.loads(json.dumps(base))
    upland.update(id="upland", title="Upland supply corridor")
    upland["provenance"]["transformationNotes"] += " Upland variation adds a slow northern crossing and ridge demand."
    for edge in upland["edges"]:
        if edge["id"].startswith("road-v"):
            edge["travelMinutes"] = 5.25
    road("bridge-north", 3, 4, 18.75)
    upland["edges"].append(edges[-1])
    upland["communities"][13]["population"] = 920
    write("upland.json", upland)

    features = []

    def polygon(kind, name, coords):
        features.append({"type": "Feature", "properties": {"kind": kind, "name": name},
                         "geometry": {"type": "Polygon", "coordinates": [coords]}})

    polygon("water", "Alder River", [(-79.938, 43.550), (-79.930, 43.550),
        (-79.932, 43.540), (-79.929, 43.530), (-79.932, 43.520), (-79.928, 43.510),
        (-79.930, 43.499), (-79.938, 43.499), (-79.935, 43.510), (-79.939, 43.520),
        (-79.936, 43.530), (-79.939, 43.540), (-79.938, 43.550)])
    polygon("park", "Westbank commons", [(-79.970, 43.519), (-79.956, 43.519),
        (-79.956, 43.509), (-79.970, 43.509), (-79.970, 43.519)])
    polygon("park", "Ridge woodland", [(-79.900, 43.543), (-79.874, 43.543),
        (-79.874, 43.537), (-79.893, 43.536), (-79.900, 43.543)])
    for r in range(4):
        for c in [0, 1, 2, 4, 5]:
            x, y = xs[c] + .0018, ys[r] - .0014
            polygon("block", "District block", [(x, y), (x + .0062, y),
                (x + .0062, y - .0048), (x, y - .0048), (x, y)])
    write("background.geojson", {"type": "FeatureCollection", "features": features})
    write("benchmark-variations.json", {"schemaVersion": "1", "variations": [
        {"id": "nominal", "scenarioId": "riverbend", "closedEdgeIds": []},
        {"id": "bridge-closed", "scenarioId": "riverbend", "closedEdgeIds": ["bridge-main"]},
        {"id": "ridge-closed", "scenarioId": "riverbend", "closedEdgeIds": ["east-ridge"]},
        {"id": "combined", "scenarioId": "riverbend", "closedEdgeIds": ["bridge-main", "orchard-return"]},
        {"id": "upland-detour", "scenarioId": "upland", "closedEdgeIds": ["bridge-main"]}]})


if __name__ == "__main__":
    build()
